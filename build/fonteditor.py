"""fonteditor.py - deterministic glyph/layout editing helpers (fontTools only; no network, no boolean ops).

Conventions: y-up font units; outer contours clockwise (TrueType); every new contour is generated by code that
depends only on per-master stem parameters, so point structure is identical across masters (variable-font safe).
"""
import math, copy
from fontTools.ttLib import TTFont
from fontTools.pens.ttGlyphPen import TTGlyphPen
from fontTools.pens.recordingPen import RecordingPen, DecomposingRecordingPen
from fontTools.pens.transformPen import TransformPen
from fontTools.pens.boundsPen import BoundsPen
from fontTools.pens.reverseContourPen import ReverseContourPen
from fontTools.pens.pointInsidePen import PointInsidePen
from fontTools.misc.roundTools import otRound
from fontTools.ttLib.tables import otTables as ot


# ----------------------------------------------------------------------------- shapes
def _r(p):
    return (otRound(p[0]), otRound(p[1]))


def _area(rp):
    pts = [pt for op, args in rp.value for pt in args if pt is not None]
    return 0.5 * sum(pts[i][0] * pts[(i + 1) % len(pts)][1] - pts[(i + 1) % len(pts)][0] * pts[i][1] for i in range(len(pts)))


def orient(rp, cw=True):
    """Return rp (single contour) with the requested winding."""
    if (_area(rp) < 0) == cw:
        return rp
    out = RecordingPen()
    rp.replay(ReverseContourPen(out))
    return out


def merge(*rps):
    out = RecordingPen()
    for rp in rps:
        out.value.extend(rp.value)
    return out


def xform(rp, m, mirror=False):
    """Affine transform with integer rounding. mirror=True flips contour direction back (use for x/y reflections)."""
    out = RecordingPen()
    rp.replay(TransformPen(out, m))
    if mirror:
        o2 = RecordingPen(); out.replay(ReverseContourPen(o2)); out = o2
    res = RecordingPen()
    for op, args in out.value:
        res.value.append((op, tuple(None if a is None else _r(a) for a in args)))
    return res


def poly(points):
    rp = RecordingPen()
    rp.moveTo(_r(points[0]))
    for p in points[1:]:
        rp.lineTo(_r(p))
    rp.closePath()
    return rp


def rect(x0, y0, x1, y1):
    return orient(poly([(x0, y0), (x0, y1), (x1, y1), (x1, y0)]), True)


def _arc_segs(cx, cy, rx, ry, a0, a1):
    n = max(1, math.ceil(abs(a1 - a0) / (math.pi / 8)))
    d = (a1 - a0) / n
    out = []
    for i in range(n):
        t0 = a0 + i * d; t1 = t0 + d; tm = (t0 + t1) / 2
        c = (cx + rx * math.cos(tm) / math.cos(d / 2), cy + ry * math.sin(tm) / math.cos(d / 2))
        e = (cx + rx * math.cos(t1), cy + ry * math.sin(t1))
        out.append((_r(c), _r(e)))
    return out


def stroke_arc(cx, cy, rx, ry, a0, a1, tv, th):
    """Variable-thickness stroke along an elliptical arc (angles in degrees). Thickness tv at the sides, th at top/bottom."""
    a0, a1 = math.radians(a0), math.radians(a1)
    ox, oy, ix, iy = rx + tv / 2, ry + th / 2, rx - tv / 2, ry - th / 2
    rp = RecordingPen()
    rp.moveTo(_r((cx + ox * math.cos(a0), cy + oy * math.sin(a0))))
    for c, e in _arc_segs(cx, cy, ox, oy, a0, a1):
        rp.qCurveTo(c, e)
    rp.lineTo(_r((cx + ix * math.cos(a1), cy + iy * math.sin(a1))))
    for c, e in _arc_segs(cx, cy, ix, iy, a1, a0):
        rp.qCurveTo(c, e)
    rp.closePath()
    return orient(rp, True)


def ring(cx, cy, orx, ory, tv, th):
    def ell(rx, ry, cw):
        rp = RecordingPen()
        rp.moveTo(_r((cx + rx, cy)))
        for c, e in _arc_segs(cx, cy, rx, ry, 0, 2 * math.pi):
            rp.qCurveTo(c, e)
        rp.closePath()
        return orient(rp, cw)
    return merge(ell(orx, ory, True), ell(orx - tv, ory - th, False))


def stroke_polyline(pts, w, miter=2.5):
    """Open polyline with flat caps and miter joins -> polygon (clockwise)."""
    n = len(pts)
    segs = []
    for i in range(n - 1):
        dx, dy = pts[i + 1][0] - pts[i][0], pts[i + 1][1] - pts[i][1]
        L = math.hypot(dx, dy); segs.append((dx / L, dy / L))
    left, right = [], []
    for i, p in enumerate(pts):
        if i == 0:
            t = segs[0]; nx, ny = -t[1], t[0]; k = 1.0
        elif i == n - 1:
            t = segs[-1]; nx, ny = -t[1], t[0]; k = 1.0
        else:
            t0, t1 = segs[i - 1], segs[i]
            nx, ny = -(t0[1] + t1[1]), (t0[0] + t1[0]); L = math.hypot(nx, ny); nx, ny = nx / L, ny / L
            cosh = nx * (-t0[1]) + ny * t0[0]; k = min(1 / max(cosh, 1e-6), miter)
        left.append((p[0] + nx * w / 2 * k, p[1] + ny * w / 2 * k)); right.append((p[0] - nx * w / 2 * k, p[1] - ny * w / 2 * k))
    return orient(poly(left + right[::-1]), True)


def embolden(rp, dx, dy, miter=1.6):
    """Move every point along the local normal by (dx,dy) (elliptical offset). Adequate for |d| <= ~25 units."""
    out = RecordingPen(); cur = []
    def flush():
        pts = [pt for op, a in cur for pt in a if pt is not None]
        # contour point list (closed)
        n = len(pts); new = []
        for i, p in enumerate(pts):
            j = (i - 1) % n
            while pts[j] == p and j != i: j = (j - 1) % n
            k = (i + 1) % n
            while pts[k] == p and k != i: k = (k + 1) % n
            a, b = pts[j], pts[k]
            t0 = (p[0] - a[0], p[1] - a[1]); t1 = (b[0] - p[0], b[1] - p[1])
            l0, l1 = math.hypot(*t0) or 1, math.hypot(*t1) or 1
            n0 = (-t0[1] / l0, t0[0] / l0); n1 = (-t1[1] / l1, t1[0] / l1)
            nx, ny = n0[0] + n1[0], n0[1] + n1[1]; L = math.hypot(nx, ny)
            if L < 1e-6: nx, ny = n0
            else: nx, ny = nx / L, ny / L
            cosh = max(nx * n0[0] + ny * n0[1], 1e-3); kk = min(1 / cosh, miter)
            new.append(_r((p[0] + nx * dx * kk, p[1] + ny * dy * kk)))
        it = iter(new)
        for op, a in cur:
            out.value.append((op, tuple(next(it) if x is not None else None for x in a)))
        cur.clear()
    for item in rp.value:
        cur.append(item)
        if item[0] in ('closePath', 'endPath'): flush()
    return out


# ----------------------------------------------------------------------------- master wrapper
class Master:
    def __init__(self, path, name):
        self.name = name
        self.font = TTFont(path, recalcTimestamp=False)
        self.glyf, self.hmtx = self.font['glyf'], self.font['hmtx']
        self.created = []          # new glyph names in creation order
        self.parent = {}           # new glyph -> parent (kerning + anchors inheritance)
        self.anchor_parent = {}    # new glyph -> parent whose mark-base anchors are copied

    # -- queries
    def gset(self): return self.font.getGlyphSet()
    def cmap(self): return self.font.getBestCmap()
    def gname(self, ch): return self.cmap()[ord(ch)] if isinstance(ch, str) else self.cmap()[ch]
    def adv(self, n): return self.hmtx[n][0]
    def bounds(self, n):
        bp = BoundsPen(self.gset()); self.gset()[n].draw(bp); return bp.bounds
    def outline(self, n):
        rp = DecomposingRecordingPen(self.gset()); self.gset()[n].draw(rp); return rp
    def inside(self, n, x, y):
        pen = PointInsidePen(self.gset(), (x, y)); self.gset()[n].draw(pen); return pen.getResult()
    def runs_x(self, n, y, step=2):
        b = self.bounds(n); rp = self.outline(n); runs = []; start = None
        for x in range(int(b[0]) - 2, int(b[2]) + 4, step):
            pen = PointInsidePen(None, (x, y)); rp.replay(pen); ins = pen.getResult()
            if ins and start is None: start = x
            if not ins and start is not None: runs.append((start, x - step)); start = None
        return runs
    def runs_y(self, n, x, step=2):
        b = self.bounds(n); rp = self.outline(n); runs = []; start = None
        for y in range(int(b[1]) - 2, int(b[3]) + 4, step):
            pen = PointInsidePen(None, (x, y)); rp.replay(pen); ins = pen.getResult()
            if ins and start is None: start = y
            if not ins and start is not None: runs.append((start, y - step)); start = None
        return runs

    # -- mutation
    def add(self, name, glyph, adv=None, cps=(), parent=None, anchor_parent=None, lsb=None):
        assert name not in self.glyf.glyphs, name
        order = list(self.font.getGlyphOrder()) + [name]
        self.font.setGlyphOrder(order); self.glyf.glyphOrder = order
        self.glyf[name] = glyph
        glyph.recalcBounds(self.glyf)
        if adv is None: adv = glyph.xMax if glyph.numberOfContours else 0
        self.hmtx[name] = (adv, glyph.xMin if (lsb is None and glyph.numberOfContours) else (lsb or 0))
        for cp in cps: self.map(cp, name)
        self.created.append(name)
        if parent: self.parent[name] = parent
        if anchor_parent or parent: self.anchor_parent[name] = anchor_parent or parent
        return name

    def map(self, cp, name):
        for tb in self.font['cmap'].tables:
            if tb.isUnicode(): tb.cmap[cp] = name

    def from_rp(self, name, rp, adv, cps=(), parent=None, anchor_parent=None):
        pen = TTGlyphPen(None); rp.replay(pen)
        return self.add(name, pen.glyph(), adv, cps, parent, anchor_parent)

    def composite(self, name, comps, adv, cps=(), parent=None, anchor_parent=None):
        pen = TTGlyphPen(self.gset())
        for g, dx, dy in comps: pen.addComponent(g, (1, 0, 0, 1, otRound(dx), otRound(dy)))
        return self.add(name, pen.glyph(), adv, cps, parent, anchor_parent)

    def replace_outline(self, name, rp, adv=None):
        pen = TTGlyphPen(None); rp.replay(pen); g = pen.glyph(); self.glyf[name] = g; g.recalcBounds(self.glyf)
        a = self.adv(name) if adv is None else adv
        self.hmtx[name] = (a, g.xMin)

    # -- layout helpers
    def gdef_class(self, name, cls):
        gd = self.font['GDEF'].table
        if gd.GlyphClassDef is None:
            gd.GlyphClassDef = ot.GlyphClassDef(); gd.GlyphClassDef.classDefs = {}
        gd.GlyphClassDef.classDefs[name] = cls

    def mark_base_subtable(self):
        for lk in self.font['GPOS'].table.LookupList.Lookup:
            if lk.LookupType == 4:
                st = lk.SubTable[0]; return getattr(st, 'ExtSubTable', st)

    def add_mark_to_class(self, mark, cls, anchor):
        st = self.mark_base_subtable()
        rec = ot.MarkRecord(); rec.Class = cls
        a = ot.Anchor(); a.Format = 1; a.XCoordinate, a.YCoordinate = anchor; rec.MarkAnchor = a
        st.MarkCoverage.glyphs.append(mark); st.MarkArray.MarkRecord.append(rec); st.MarkArray.MarkCount += 1
        self.gdef_class(mark, 3)

    def inherit_anchors(self):
        """Give every new glyph with an anchor parent the parent's mark-to-base anchors (appended in glyph-id order)."""
        st = self.mark_base_subtable(); cov = st.BaseCoverage.glyphs
        idx = {g: r for g, r in zip(cov, st.BaseArray.BaseRecord)}
        order = {g: i for i, g in enumerate(self.font.getGlyphOrder())}
        for g in sorted(self.anchor_parent, key=lambda x: order[x]):
            p = self.anchor_parent[g]
            if p in idx and g not in idx:
                rec = copy.deepcopy(idx[p]); cov.append(g); st.BaseArray.BaseRecord.append(rec); idx[g] = rec
        st.BaseArray.BaseCount = len(st.BaseArray.BaseRecord)

    def inherit_kerning(self):
        order = {g: i for i, g in enumerate(self.font.getGlyphOrder())}
        gpos = self.font['GPOS'].table
        kl = [i for fr in gpos.FeatureList.FeatureRecord if fr.FeatureTag == 'kern' for i in fr.Feature.LookupListIndex]
        newg = sorted(self.parent, key=lambda x: order[x])
        for li in kl:
            for sub in gpos.LookupList.Lookup[li].SubTable:
                st = getattr(sub, 'ExtSubTable', sub)
                if st.Format == 1:
                    cov = st.Coverage.glyphs; ps = {g: s for g, s in zip(cov, st.PairSet)}
                    for g in newg:                                   # as second glyph
                        p = self.parent[g]
                        for s in st.PairSet:
                            for rec in list(s.PairValueRecord):
                                if rec.SecondGlyph == p:
                                    r2 = copy.deepcopy(rec); r2.SecondGlyph = g; s.PairValueRecord.append(r2)
                            s.PairValueRecord.sort(key=lambda r: order[r.SecondGlyph]); s.PairValueCount = len(s.PairValueRecord)
                    for g in newg:                                   # as first glyph
                        p = self.parent[g]
                        if p in ps and g not in ps:
                            s = copy.deepcopy(ps[p]); cov.append(g); st.PairSet.append(s); ps[g] = s
                    st.PairSetCount = len(st.PairSet)
                elif st.Format == 2:
                    c1, c2 = st.ClassDef1.classDefs, st.ClassDef2.classDefs
                    for g in newg:
                        p = self.parent[g]
                        if p in st.Coverage.glyphs and g not in st.Coverage.glyphs:
                            st.Coverage.glyphs.append(g)
                            if p in c1: c1[g] = c1[p]
                        if p in c2: c2[g] = c2[p]

    def finalize(self):
        self.inherit_anchors(); self.inherit_kerning()


# ----------------------------------------------------------------------------- layout merge (feaLib scratch -> main)
def _shift_nested(lookup, off):
    for sub in lookup.SubTable:
        st = getattr(sub, 'ExtSubTable', sub)
        for attr in ('SubstLookupRecord', 'PosLookupRecord'):
            for obj in _walk(st):
                for rec in getattr(obj, attr, []) or []:
                    rec.LookupListIndex += off


def _walk(o):
    yield o
    for attr in ('ChainSubRuleSet', 'ChainSubClassSet', 'ChainSubRule', 'ChainSubClassRule', 'SubRuleSet', 'SubClassSet', 'SubRule', 'SubClassRule'):
        v = getattr(o, attr, None)
        if v is None: continue
        for x in (v if isinstance(v, list) else [v]):
            if x is not None: yield from _walk(x)


def merge_layout(main, scratch, tag):
    M, S = main[tag].table, scratch[tag].table
    off = len(M.LookupList.Lookup)
    for lk in S.LookupList.Lookup: _shift_nested(lk, off)
    M.LookupList.Lookup.extend(S.LookupList.Lookup); M.LookupList.LookupCount = len(M.LookupList.Lookup)
    for fr in S.FeatureList.FeatureRecord:
        shifted = [i + off for i in fr.Feature.LookupListIndex]
        same = [f for f in M.FeatureList.FeatureRecord if f.FeatureTag == fr.FeatureTag]
        if same:
            for f in same:
                f.Feature.LookupListIndex = sorted(set(f.Feature.LookupListIndex) | set(shifted)); f.Feature.LookupCount = len(f.Feature.LookupListIndex)
        else:
            nf = ot.FeatureRecord(); nf.FeatureTag = fr.FeatureTag; nf.Feature = ot.Feature(); nf.Feature.FeatureParams = None
            nf.Feature.LookupListIndex = shifted; nf.Feature.LookupCount = len(shifted)
            M.FeatureList.FeatureRecord.append(nf); M.FeatureList.FeatureCount = len(M.FeatureList.FeatureRecord)
            new_i = len(M.FeatureList.FeatureRecord) - 1
            for sr in M.ScriptList.ScriptRecord:
                for ls in [sr.Script.DefaultLangSys] + [l.LangSys for l in sr.Script.LangSysRecord]:
                    if ls is not None: ls.FeatureIndex.append(new_i); ls.FeatureCount = len(ls.FeatureIndex)
    _sort_features(M)


def _sort_features(T):
    recs = T.FeatureList.FeatureRecord
    order = sorted(range(len(recs)), key=lambda i: (recs[i].FeatureTag, i))
    remap = {old: new for new, old in enumerate(order)}
    T.FeatureList.FeatureRecord = [recs[i] for i in order]
    for sr in T.ScriptList.ScriptRecord:
        for ls in [sr.Script.DefaultLangSys] + [l.LangSys for l in sr.Script.LangSysRecord]:
            if ls is not None:
                ls.FeatureIndex = sorted(remap[i] for i in ls.FeatureIndex); ls.FeatureCount = len(ls.FeatureIndex)
