"""Regenerates RELEASE_READINESS.md from measured results and v6_ledger.json.

It never computes a quality score: the plans' target (9.9/10 = 98/100) cannot be claimed from file-integrity gates.
In --mode release it exits 1 unless every gate passed and every BLOCKER ledger item is DONE."""
import os, sys, json, argparse, datetime
import buildenv

BASE = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))


def load(p, default=None):
    try: return json.load(open(f'{BASE}/{p}'))
    except Exception: return default


def main():
    ap = argparse.ArgumentParser(); ap.add_argument('--mode', default='dev'); ap.add_argument('--design-open', type=int, default=0)
    a = ap.parse_args()
    led = load('v6_ledger.json'); qa = load('reports/qa/qa_gates.json', {}); it = load('reports/qa/interp_dense.json', {})
    cf = load('reports/qa/confusables_proto.json', {}); man = load('reports/build_reports/release_manifest.json', {})
    wv = load('reports/qa/weights_validity.json', {})
    items = led['items']
    cnt = {}
    for i in items: cnt[i['status']] = cnt.get(i['status'], 0) + 1
    qa_fail = [k for k, v in qa.items() if not v['pass']]
    conf_fail = [k for k, v in (cf.get('gate') or {}).items() if not v['pass']]
    blockers = [i for i in items if i['blocker'] and i['status'] != 'DONE']
    day = datetime.datetime.fromtimestamp(int(os.environ['SOURCE_DATE_EPOCH']), datetime.timezone.utc).strftime('%Y-%m-%d')
    L = []
    L += ['# Stackra Sans V6: release readiness', '',
          f'Generated by `build/scripts/release_readiness.py` from measured results (snapshot {day}). Do not edit by hand.', '',
          '## Verdict', '',
          '**9.9/10 (98/100) is NOT claimable.** The gates below prove file integrity. They do not measure design quality, '
          'language correctness, rendering on real devices or legal status, and 8 BLOCKER steps need people or legal decisions.', '',
          f'Ledger (200 steps = plan 1: 100 V5 requirements + plan 2: 100-step V4 roadmap): '
          + ', '.join(f'{k} {cnt.get(k, 0)}' for k in ('DONE', 'PARTIAL', 'OPEN', 'HUMAN', 'NA')) + '.', '',
          '## Measured gates this run', '',
          f'- Integrity gates (qa_font.py): {len(qa) - len(qa_fail)}/{len(qa)} pass' + (f'. FAILING: {qa_fail}' if qa_fail else ''),
          f'- Dense interpolation (every {it.get("step")} wght units): ' + ('PASS' if it.get('pass') else f'FAIL ({len(it.get("failures", []))} glyph/weight failures)'),
          f'- Confusables @14px (registered maxima): ' + ('PASS' if not conf_fail else 'FAIL ' + ', '.join(f'{k} {cf["gate"][k]["value"]} > {cf["gate"][k]["max"]}' for k in conf_fail)),
          f'- Shipped weights: {man.get("shipped_weights")}; experimental (not shipped): {[w for w, v in (wv.get("weights") or {}).items() if not v["public"]]}',
          f'- WOFF2: {wv.get("woff2")}', '']
    L += ['### File-size budgets', '']
    for k, v in (man.get('size_budgets') or {}).items():
        L.append(f'- `{k}`: ' + (f'{v["bytes"]} / {v["limit"]} bytes: {"PASS" if v["pass"] else "FAIL"}' if v['bytes'] is not None else f'NOT MEASURED ({v.get("status")})'))
    L += ['', '## Blockers still open', '']
    for i in blockers: L.append(f'- {i["id"]} {i["title"]}: **{i["status"]}**. {i["note"]}')
    L += ['', '## Full ledger', '', '| ID | Status | Step | Note |', '|---|---|---|---|']
    for i in items:
        L.append(f'| {i["id"]} | {i["status"]} | {i["title"].replace("|", "/")} | {i["note"].replace("|", "/")} |')
    open(f'{BASE}/RELEASE_READINESS.md', 'w', encoding='utf-8').write('\n'.join(L) + '\n')
    print(f'readiness: {cnt}; integrity gates failing: {len(qa_fail)}; design gates failing: {len(conf_fail)}; blockers open: {len(blockers)}')
    if a.mode == 'release' and (qa_fail or conf_fail or not it.get('pass') or blockers or a.design_open):
        print('RELEASE MODE: not releasable (see RELEASE_READINESS.md)', file=sys.stderr); return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
